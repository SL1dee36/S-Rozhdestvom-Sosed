export const STORAGE_KEY = 'zarechnoe_map_overrides_v2';

function cloneData(data) {
    return JSON.parse(JSON.stringify(data || {}));
}

export function normalizeMapOverrides(raw) {
    const src = raw && typeof raw === 'object' ? raw : {};
    return {
        version: src.version || 1,
        updatedAt: src.updatedAt || null,
        modifiedObjects: src.modifiedObjects && typeof src.modifiedObjects === 'object' ? cloneData(src.modifiedObjects) : {},
        modifiedLights: src.modifiedLights && typeof src.modifiedLights === 'object' ? cloneData(src.modifiedLights) : {},
        addedObjects: Array.isArray(src.addedObjects) ? cloneData(src.addedObjects) : [],
        addedLights: Array.isArray(src.addedLights) ? cloneData(src.addedLights) : [],
        gameplay: src.gameplay && typeof src.gameplay === 'object' ? cloneData(src.gameplay) : {}
    };
}

export function getEffectiveMapOverrides() {
    const ignoreLocal = typeof window !== 'undefined' && !!window.__IGNORE_LOCAL_OVERRIDES__;
    if (!ignoreLocal && typeof localStorage !== 'undefined') {
        try {
            const raw = localStorage.getItem(STORAGE_KEY);
            if (raw) {
                const parsed = JSON.parse(raw);
                if (parsed && typeof parsed === 'object') {
                    return normalizeMapOverrides(parsed);
                }
            }
        } catch (err) {
            console.warn('MapOverrides: Failed to parse localStorage overrides:', err);
        }
    }
    return normalizeMapOverrides(MAP_OVERRIDES);
}

export function saveOverridesToLocalStorage(data) {
    if (typeof localStorage === 'undefined') return false;
    try {
        const normalized = normalizeMapOverrides(data);
        localStorage.setItem(STORAGE_KEY, JSON.stringify(normalized));
        return true;
    } catch (err) {
        console.warn('MapOverrides: Failed to write localStorage overrides:', err);
        return false;
    }
}

export function clearLocalStorageOverrides() {
    if (typeof localStorage === 'undefined') return;
    try {
        localStorage.removeItem(STORAGE_KEY);
    } catch (err) {
        console.warn('MapOverrides: Failed to clear localStorage overrides:', err);
    }
}

export function serializeMapOverridesToJS(data) {
    const normalized = normalizeMapOverrides({
        ...data,
        version: 1,
        updatedAt: new Date().toISOString()
    });
    const jsonBlock = JSON.stringify(normalized, null, 4);
    const lines = [
        `export const MAP_OVERRIDES = ${jsonBlock};`,
        '',
        "export const STORAGE_KEY = 'zarechnoe_map_overrides_v2';",
        '',
        cloneData.toString(),
        '',
        `export ${normalizeMapOverrides.toString()}`,
        '',
        `export ${getEffectiveMapOverrides.toString()}`,
        '',
        `export ${saveOverridesToLocalStorage.toString()}`,
        '',
        `export ${clearLocalStorageOverrides.toString()}`,
        '',
        `export ${serializeMapOverridesToJS.toString()}`,
        ''
    ];
    return lines.join('\n');
}
